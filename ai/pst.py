# Map piece types to their PST
PST_MAP = {
    chess.PAWN: PAWN_PST,
    chess.KNIGHT: KNIGHT_PST,
    chess.BISHOP: BISHOP_PST,
    chess.ROOK: ROOK_PST,
    chess.QUEEN: QUEEN_PST,
}


def get_pst_value(piece_type: int, square: int, is_white: bool, is_endgame: bool = False) -> int:
    """
    Get the piece-square table value for a piece

    Args:
        piece_type: chess.PAWN, chess.KNIGHT, etc.
        square: square index (0-63)
        is_white: True if the piece is white
        is_endgame: True if in endgame phase (affects king PST)
    """
    if piece_type == chess.KING:
        table = KING_ENDGAME_PST if is_endgame else KING_MIDDLE_PST
    else:
        table = PST_MAP.get(piece_type)
        if table is None:
            return 0

    # Get rank and file from square
    rank = square // 8
    file = square % 8

    # For black pieces, mirror the table vertically
    if not is_white:
        rank = 7 - rank

    return table[rank][file]